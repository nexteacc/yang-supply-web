"""Split the upstream Gothic OTF into disjoint WOFF subsets for on-demand loading.
Usage: python scripts/prepare-chill-gothic.py /path/to/ChillDINGothic_Std.otf
English variable TTF and OFL.txt are copied unchanged from upstream.
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
import sys
root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
out = root / 'public/fonts/chill'
all_chars = set(TTFont(source).getBestCmap())
site_text = ''.join(p.read_text() for p in (root / 'src').rglob('*') if p.suffix in {'.tsx', '.ts'})
common = all_chars & set(map(ord, site_text))
rest = sorted(all_chars - common)
groups = [sorted(common)] + [rest[i:i+1024] for i in range(0, len(rest), 1024)]
def unicode_ranges(chars):
    spans = []
    start = end = chars[0]
    for c in chars[1:]:
        if c == end + 1:
            end = c
        else:
            spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
            start = end = c
    spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ','.join(spans)

rules = ['/* Generated by scripts/prepare-chill-gothic.py; upstream SIL OFL 1.1. */']
for i, chars in enumerate(groups):
    f = TTFont(source)
    options = subset.Options()
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=chars)
    sub.subset(f)
    # OFL reserves the upstream names: name the web subsets independently.
    for record in f['name'].names:
        values = {1: 'Yang Supply Gothic Web', 2: 'Regular', 3: 'YangSupplyGothicWeb-Regular',
                  4: 'Yang Supply Gothic Web Regular', 6: 'YangSupplyGothicWeb-Regular',
                  16: 'Yang Supply Gothic Web', 17: 'Regular'}
        if record.nameID in values:
            record.string = values[record.nameID].encode(record.getEncoding())
    if 'CFF ' in f:
        cff = f['CFF '].cff
        cff.fontNames = ['YangSupplyGothicWeb-Regular']
        cff.topDictIndex[0].FamilyName = 'Yang Supply Gothic Web'
        cff.topDictIndex[0].FullName = 'Yang Supply Gothic Web Regular'
    f.flavor = 'woff' 
    name = f'YangGothicWeb-{i:02}.woff'
    f.save(out / name)
    ranges = unicode_ranges(chars)
    rules.append('@font-face {\n  font-family: "Yang Supply Gothic Web";\n  src: url("/fonts/chill/'+name+'") format("woff");\n  font-weight: 400;\n  font-style: normal;\n  font-display: swap;\n  unicode-range: '+ranges+';\n}')
(root / 'src/app/chill-gothic.css').write_text('\n\n'.join(rules)+'\n')
print('Generated',len(groups),'subsets; current-site subset:',(out/'YangGothicWeb-00.woff').stat().st_size,'bytes')
